// python.json is what bot/harness/queue.py answers for each input (generated by running it).
func expected(t *testing.T) *pyjson.Object {
	t.Helper()
	raw, err := os.ReadFile("testdata/python.json")
	if err != nil {
		t.Fatal(err)
	}
	data, err := pyjson.Loads(raw)
	if err != nil {
		t.Fatal(err)
	}
	return data.(*pyjson.Object)
}

func set(names []any) map[string]bool {
	out := map[string]bool{}
	for _, n := range names {
		out[n.(string)] = true
	}
	return out
}

func TestPartOfMatchesPython(t *testing.T) {
	for _, pair := range expected(t).List("part_of") {
		title := pair.([]any)[0].(string)
		var got any
		if name, total, n, ok := PartOf(title); ok {
			got = []any{name, total, n}
		}
		if g, w := pyjson.Dumps(got), pyjson.Dumps(pair.([]any)[1]); g != w {
			t.Errorf("PartOf(%q) = %s, want %s", title, g, w)
		}
	}
}

