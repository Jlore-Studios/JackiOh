func TestThreadsAndRepliesMatchPython(t *testing.T) {
	data := expected(t)
	for _, row := range data.List("owner") {
		r := row.([]any)
		thread := r[0].(*pyjson.Object)
		owner := ""
		if other := Owner(thread); other != nil {
			owner = other.Name
		}
		var names []string
		for name := range LabelNames(thread) {
			names = append(names, name)
		}
		sort.Strings(names)
		if owner != r[1] || pyjson.Dumps(pyjson.ListOf(names)) != pyjson.Dumps(r[2]) {
			t.Errorf("thread %s: owner %q names %v, want %v %v", pyjson.Dumps(thread), owner, names, r[1], r[2])
		}
	}
	for _, row := range data.List("merge_title") {
		r := row.([]any)
		pull := r[0].(*pyjson.Object)
		if got := MergeTitle(pull, "squash"); got != r[1] {
			t.Errorf("MergeTitle(%s, squash) = %q, want %q", pyjson.Dumps(pull), got, r[1])
		}
		if got := MergeTitle(pull, "merge"); got != r[2] {
			t.Errorf("MergeTitle(%s, merge) = %q, want %q", pyjson.Dumps(pull), got, r[2])
		}
	}
	squishy := cfgOthers(config.Others)[0]
	if got := OwnerReply(9, squishy); got != data.Str("owner_reply") {
		t.Errorf("OwnerReply = %q, want %q", got, data.Str("owner_reply"))
	}
	if got := PartsReply(3, []int{4, 5}); got != data.Str("parts_reply") {
		t.Errorf("PartsReply = %q, want %q", got, data.Str("parts_reply"))
	}
	branches := []string{BranchForIssue(12), WipBranch(13)}
	if !slices.Equal(branches, pyjson.Strings(data.Get("branches"))) {
		t.Errorf("branches %v, want %v", branches, data.Get("branches"))
	}
}

func TestCandidateOrder(t *testing.T) {
	c := func(number int, kind string, forced bool, priority int, at string) *Candidate {
		x := NewCandidate(number, kind, "", forced, at)
		x.Priority = priority
		return x
	}
	queue := []*Candidate{
		c(1, "build", false, NoPriority, "2026-01-01"), c(2, "revise", false, NoPriority, "2026-01-02"),
		c(3, "review", false, NoPriority, "2026-01-03"), c(4, "build", true, 3, "2026-01-04"),
		c(5, "build", false, 0, "2026-01-05"), c(6, "build", false, NoPriority, "2026-01-01"),
	}
	sort.SliceStable(queue, func(i, j int) bool { return candidateLess(queue[i], queue[j]) })
	var got []int
	for _, x := range queue {
		got = append(got, x.Number)
	}
	if want := []int{4, 5, 3, 2, 1, 6}; !slices.Equal(got, want) {
		t.Errorf("order %v, want %v", got, want)
	}
	if x := NewCandidate(1, "build", "", false, ""); x.Difficulty != "medium" || x.Priority != 2 || !x.Rated {
		t.Errorf("defaults %+v", x)
	}
}
