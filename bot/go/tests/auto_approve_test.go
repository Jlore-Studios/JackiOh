// ---------------------------------------------------------------------------- WindowTests

func TestAutoApprove_DecisionsJoinTheWindowEachOnceAsItEnded(t *testing.T) {
	h := ratingDayHarness(t)
	h.gh.AddIssue(12, fakes.Issue{Title: "Night bot: tune the sweep", Labels: []string{config.LabelSuggestion}})
	h.gh.AddIssue(13, fakes.Issue{Title: "Patch: a smarter AI", Labels: []string{config.LabelSuggestion}})
	flowAsk(h, 12, "approve", 63)
	flowAsk(h, 13, "approve", 64)
	// #12 is handed to people as work the bot cannot do, so it came to nothing after all.
	h.night(declinedPlanRunner(ratingRatedPlan("medium", []string{"bot/harness/sweep.py"}, "")))
	decided := declined.DecidedEntries(h.ctx.Store.Load())
	verdictOf := map[any]any{}
	for _, d := range decided {
		verdictOf[d.Get("number")] = d.Get("verdict")
	}
	assertEqual(t, len(decided), 2)
	assertEqual(t, verdictOf, map[any]any{12: declined.VerdictCameToNothing, 13: declined.VerdictApproved})
	lines := declined.DecidedLines(h.ctx.Store.Load(), 50)
	assertTrue(t, strings.HasPrefix(lines, "The latest 2: 1 approved by a person, 1 came to nothing."), lines)
	assertIn(t, "#13 Patch: a smarter AI: approved (approved by @jgoetzmann)", lines)
	assertEqual(t, declined.DecidedLines(h.ctx.Store.Load(), 0), "(none)")
	one := declined.DecidedLines(h.ctx.Store.Load(), 1)
	assertTrue(t, strings.HasPrefix(one, "The latest 1:"), one)
}

