func TestAutoApprove_ACommentOrAThumbsDownLeavesItToAPerson(t *testing.T) {
	h := newFlowHarness(t)
	awaiting(h, 41, 25*time.Hour)
	awaiting(h, 42, 25*time.Hour)
	awaiting(h, 43, 25*time.Hour)
	h.gh.AddComment(41, "Hmm, let me think about this one.")
	h.gh.Threads.Item(42).Set("reactions", pyjson.New("+1", 0, "-1", 1))
	h.gh.UpdateIssue(43, pyjson.New("state", "closed", "state_reason", "not_planned"))
	notes := plan.AutoApprove(h.ctx)
	assertEqual(t, notes, []string{"#41 waits for a person: a comment by @jgoetzmann",
		"#42 waits for a person: a 👎 on it"})
	for _, n := range []int{41, 42} {
		assertIn(t, config.LabelSuggestion, h.gh.LabelNames(n))
		assertNotIn(t, config.LabelBuild, h.gh.LabelNames(n))
	}
	assertEqual(t, len(pendingAuto(h)), 0) // each waits for its vote as any suggestion does
}

func TestAutoApprove_AtMostPerDay(t *testing.T) {
	h := newFlowHarness(t)
	for n := 50; n < 55; n++ {
		awaiting(h, n, 30*time.Hour)
	}
	h.ctx.Store.Update(func(s *pyjson.Object) any {
		// One went ahead 2 hours ago, and one 25 hours ago, which no longer counts.
		s.Obj("suggest").Set("auto_approved", []any{clock.ISO(h.ctx.Now().Add(-25 * time.Hour)),
			clock.ISO(h.ctx.Now().Add(-2 * time.Hour))})
		return nil
	}, "state")
	notes := plan.AutoApprove(h.ctx)
	assertEqual(t, notes, []string{"#50 approved itself", "#51 approved itself",
		"#52 waits: 3 approved themselves in the last day already"})
	assertEqual(t, pendingAuto(h), []string{"52", "53", "54"})
	assertEqual(t, len(h.ctx.Store.Load().Obj("suggest").List("auto_approved")), 3)
}
