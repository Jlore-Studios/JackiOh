func TestAutoApprove_TheJudgeReadsTheWindowAndItsWordLandsOnTheIssue(t *testing.T) {
	h := newFlowHarness(t, flowHarnessOpts{Env: crossAll})
	h.gh.AddIssue(30, fakes.Issue{Title: "Patch: an old idea", Labels: []string{config.LabelSuggestion}})
	flowAsk(h, 30, "reject\nWhy: nothing acts on it.", 61)
	testsupport.IdleFor(h.ctx)
	r := autoSurvey(`<!-- judgements: [{"n": 1, "verdict": "approve", "why": "It fixes a rules bug."}, `+
		`{"n": 2, "verdict": "person", "why": "A design call."}] -->`,
		"Patch: the AI counts Lifesteal", "Patch: a puzzle mode")
	h.night(r)
	judge := r.Calls[1]
	assertEqual(t, judge.Role, "judge")
	assertIn(t, "## The latest decisions on suggestions", judge.Prompt)
	assertIn(t, "#30 Patch: an old idea: came to nothing (rejected by @jgoetzmann). Why: nothing acts on it.",
		judge.Prompt)
	assertIn(t, "### Suggestion 2: Patch: a puzzle mode", judge.Prompt)
	opened := openSuggestionsByTitle(h)
	approve, person := opened["Patch: the AI counts Lifesteal"], opened["Patch: a puzzle mode"]
	assertIn(t, "**Judge:** would approve it: It fixes a rules bug. With no vote, no comment and no 👎",
		approve.Str("body"))
	assertIn(t, "at `priority:low` (at most 3 a day)", approve.Str("body"))
	assertIn(t, "**Judge:** leaves it to a person: A design call.", person.Str("body"))
	assertEqual(t, pendingAuto(h), []string{strconv.Itoa(approve.Int("number"))})
}

func TestAutoApprove_AJudgeThatFailsLosesNoSuggestion(t *testing.T) {
	h := newFlowHarness(t, flowHarnessOpts{Env: crossAll})
	testsupport.IdleFor(h.ctx)
	r := autoSurvey("", "Patch: one idea")
	h.night(r)
	opened := openSuggestionsByTitle(h)
	assertEqual(t, len(opened), 1)
	assertNotIn(t, "**Judge:**", opened["Patch: one idea"].Str("body"))
	assertEqual(t, len(pendingAuto(h)), 0)
}

func TestAutoApprove_OffJudgesNothing(t *testing.T) {
	suggestions := testsupport.RawConfig().Obj("suggestions").Copy()
	suggestions.Set("auto_approve", pyjson.New("enabled", false))
	h := newFlowHarness(t, flowHarnessOpts{Env: crossAll, Overrides: pyjson.New("suggestions", suggestions)})
	testsupport.IdleFor(h.ctx)
	r := autoSurvey(`<!-- judgements: [{"n": 1, "verdict": "approve"}] -->`, "Patch: one idea")
	h.night(r)
	assertEqual(t, len(r.Calls), 1)
	assertNotIn(t, "**Judge:**", openSuggestionsByTitle(h)["Patch: one idea"].Str("body"))
}

func TestAutoApprove_TheJudgementsAreRead(t *testing.T) {
	text := `<!-- judgements: [{"n": 1, "verdict": " Approve ", "why": "a\nb"}, {"n": 1, "verdict": "person"}, ` +
		`{"n": 2, "verdict": "maybe"}, {"n": 9, "verdict": "approve"}, {"n": "x"}] -->`
	found := verdicts.Judgements(text, 3)
	assertEqual(t, len(found), 2)
	assertEqual(t, []any{found[1].Approve, found[1].Why, found[2].Approve}, []any{true, "a b", false})
	assertEqual(t, len(verdicts.Judgements("no header", 3)), 0)
}

