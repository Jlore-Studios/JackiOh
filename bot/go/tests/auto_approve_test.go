// autoSurvey is a survey that suggests `titles`, and a judge that answers `judged` (none: no
// judge handler, so its call fails).
func autoSurvey(judged string, titles ...string) *runner.FakeRunner {
	items := []string{}
	for _, title := range titles {
		items = append(items, pyjson.Dumps(pyjson.New("title", title, "body", "## Why\nx", "class", "ai")))
	}
	handlers := map[string][]runner.Handler{
		"suggest": {workReviewer("<!-- suggestions: [" + strings.Join(items, ",") + "] -->")}}
	if judged != "" {
		handlers["judge"] = []runner.Handler{workReviewer(judged)}
	}
	return runner.NewFakeRunner(handlers)
}

// openSuggestionsByTitle is each open suggestion's body, by its title.
func openSuggestionsByTitle(h *flowHarness) map[string]*pyjson.Object {
	out := map[string]*pyjson.Object{}
	for _, thread := range h.gh.Threads.Values() {
		for _, label := range thread.List("labels") {
			if pyjson.Obj(label).Get("name") == config.LabelSuggestion && thread.Get("state") == "open" {
				out[pyjson.Str(thread.Get("title"))] = thread
			}
		}
	}
	return out
}

// awaiting adds open suggestion `number`, which the judge would approve, opened `ago`.
func awaiting(h *flowHarness, number int, ago time.Duration, labels ...string) {
	h.gh.AddIssue(number, fakes.Issue{Title: "Idea " + strconv.Itoa(number),
		Labels: append([]string{config.LabelSuggestion}, labels...)})
	h.ctx.Store.Update(func(s *pyjson.Object) any {
		plan.MarkAutoApprove(s, number, clock.ISO(h.ctx.Now().Add(-ago)), "it fixes a bug players hit.")
		return nil
	}, "state")
}

func pendingAuto(h *flowHarness) []string {
	return h.ctx.Store.Load().Obj("suggest").Obj("auto").Keys()
}

