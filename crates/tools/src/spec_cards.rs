//! `spec index`'s second file, `spec/CARDS.md` (#3804): every card and token by the keywords its
//! faces print, by its tags, and by the named pools it is in, written from the catalog this build
//! compiles and from `jackioh_cards::POOLS`, so no spec row lists a keyword's or a pool's cards by hand.
//!
//! The spec states the rule that decides each list ("every non-token card tagged Jlockeed") and links
//! the list's heading here, `[[CARDS#jlockeed]]`; `spec check` holds each such link to a heading this
//! file has ([`headings`]). Like `spec/INDEX.md` it is the daily fold's to keep (`spec fold` runs
//! `index`), so a card branch never writes it and never conflicts on it: a card merged since the last
//! fold is in the catalog and not here yet.
//!
//! A pool's "drawn by" is every script under `crates/cards/src/scripts/` whose code, above its
//! `#[cfg(test)]` and with its comments and strings blanked, calls the pool's function
//! (`NamedPool::call`), so that list is not kept by hand either.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use jackioh_cards::{CATALOG, POOLS};
use jackioh_engine::wire::set_row;
use jackioh_engine::{CardDef, KeywordKind, Tag, has_keyword};

use crate::classify::script_id;

/// The file `index` writes beside `spec/INDEX.md`, in `spec/`, and the note stem a link names.
pub(crate) const CARDS_NOTE: &str = "CARDS.md";

/// The stem a `[[CARDS#…]]` link names.
pub(crate) const CARDS_STEM: &str = "CARDS";

/// The card scripts a pool's "drawn by" is read from, relative to the root.
const SCRIPTS_REL: &str = "crates/cards/src/scripts";

/// The section of every keyword's row.
const KEYWORDS_HEADING: &str = "Keywords";

/// The section of every tag's row.
const TAGS_HEADING: &str = "Tags";

/// The section of the named pools, each a heading of its own under it.
const POOLS_HEADING: &str = "Pools";

/// What a cell with no card in it says.
const NONE: &str = "none";

const HEADER: &str = "# Cards by keyword, tag and pool\n\nGenerated by `cargo jackioh spec index` from the catalog the build compiles (`crates/cards/catalog.json`) and the named pools of `crates/cards/src/query.rs` (`POOLS`), and rewritten on `main` every day by `spec fold` (`.github/workflows/spec-fold.yml`), so a card merged since is in the catalog and not here yet: edit the catalog, a script or a pool, never this file (#3804). The spec states the rule that decides each list and links its heading (`[[CARDS#jlockeed]]`); this file holds the cards the rule finds today.\n\nA card is written as the spec writes it, its set's abbreviation and its index (`S #94`, a Core card's with no abbreviation, a shared token's index as it is, `T-rush`), then its name, in catalog order: set by set, each card in §5 index order with its tokens after it.\n";

/// The headings a `[[CARDS#…]]` link may name: the three sections and every named pool's.
pub(crate) fn headings() -> BTreeSet<String> {
    [KEYWORDS_HEADING, TAGS_HEADING, POOLS_HEADING]
        .into_iter()
        .chain(POOLS.iter().map(|pool| pool.name))
        .map(str::to_string)
        .collect()
}

/// A card as the spec writes it: `S #94 Tmack Trav`, `#20 Pointmaster`, `T-rush Rush Token`.
fn label(def: &CardDef) -> String {
    let prefix = set_row(def.set)
        .abbreviation
        .map(|abbreviation| format!("{abbreviation} "))
        .unwrap_or_default();
    let index = if def.index.starts_with(|c: char| c.is_ascii_digit()) {
        format!("#{}", def.index)
    } else {
        def.index.clone()
    };
    format!("{prefix}{index} {}", def.name).replace('|', "\\|")
}

/// Labels joined for a cell or a line, or `none`.
fn joined(labels: impl IntoIterator<Item = String>) -> String {
    let labels: Vec<String> = labels.into_iter().collect();
    if labels.is_empty() {
        NONE.to_string()
    } else {
        labels.join(", ")
    }
}

/// Every card and token in catalog order.
fn catalog() -> impl Iterator<Item = &'static CardDef> {
    CATALOG.values()
}

/// `defs` in catalog order, whatever order they came in (a pool under the testkit's pool probe comes
/// back rotated, #3117).
fn in_catalog_order(defs: &[&CardDef]) -> Vec<&'static CardDef> {
    let ids: BTreeSet<&str> = defs.iter().map(|def| def.id.as_str()).collect();
    catalog().filter(|def| ids.contains(def.id.as_str())).collect()
}

/// The keywords' table: each keyword the engine knows but a retired one, the cards and the tokens
/// that print it on either face, `(Radiant)` after one only its Radiant face prints.
fn keyword_rows(out: &mut String) -> Result<()> {
    writeln!(out, "## {KEYWORDS_HEADING}\n")?;
    writeln!(
        out,
        "The cards and tokens that print each keyword on either face, as the catalog's `keywords` hold them; `(Radiant)` marks one only its Radiant face prints. A keyword a card gives, lends or gains in play is the rules' to name ([[§6.1]]), and a keyword no card prints says {NONE}.\n"
    )?;
    writeln!(out, "| Keyword | Cards | Tokens |\n| --- | --- | --- |")?;
    for kind in KeywordKind::ALL
        .iter()
        .filter(|kind| !KeywordKind::RETIRED.contains(*kind))
    {
        let mut cards = Vec::new();
        let mut tokens = Vec::new();
        for def in catalog() {
            let base = has_keyword(&def.base.keywords, *kind);
            let radiant = has_keyword(&def.radiant.keywords, *kind);
            if !base && !radiant {
                continue;
            }
            let entry = if base {
                label(def)
            } else {
                format!("{} (Radiant)", label(def))
            };
            if def.is_token() {
                tokens.push(entry);
            } else {
                cards.push(entry);
            }
        }
        writeln!(
            out,
            "| {} | {} | {} |",
            kind.as_str(),
            joined(cards),
            joined(tokens)
        )?;
    }
    Ok(())
}

/// The tags' table: each tag, its cards and its tokens.
fn tag_rows(out: &mut String) -> Result<()> {
    writeln!(out, "\n## {TAGS_HEADING}\n")?;
    writeln!(
        out,
        "The cards and tokens that carry each tag ([[§5]]); a pool that names a tag takes its cards, and its tokens only when it asks for them ([[§5.1]], [[R382]]).\n"
    )?;
    writeln!(out, "| Tag | Cards | Tokens |\n| --- | --- | --- |")?;
    for tag in Tag::ALL {
        let (tokens, cards): (Vec<&CardDef>, Vec<&CardDef>) = catalog()
            .filter(|def| def.tags.contains(tag))
            .partition(|def| def.is_token());
        writeln!(
            out,
            "| {} | {} | {} |",
            tag.as_str(),
            joined(cards.into_iter().map(label)),
            joined(tokens.into_iter().map(label))
        )?;
    }
    Ok(())
}

/// Every card script under `scripts` and the catalog id it scripts, its code above its tests with its
/// comments and strings blanked. A root with no scripts (a test's tree of spec notes alone) has none,
/// so its pools say they are drawn by none.
fn script_code(scripts: &Path) -> Result<Vec<(String, String)>> {
    let mut files = Vec::new();
    if scripts.is_dir() {
        walk(scripts, &mut files)?;
    }
    let mut out = Vec::new();
    for file in files
        .iter()
        .filter(|path| path.extension().is_some_and(|ext| ext == "rs"))
    {
        let source = fs::read_to_string(file).with_context(|| format!("reading {}", file.display()))?;
        let Some(id) = script_id(&source) else {
            continue;
        };
        let above_tests = source.split("#[cfg(test)]").next().unwrap_or("");
        out.push((id, crate::spec::rust_code_only(above_tests)));
    }
    Ok(out)
}

/// Every file under `dir`, recursively and in name order.
fn walk(dir: &Path, out: &mut Vec<PathBuf>) -> Result<()> {
    let mut paths: Vec<PathBuf> = fs::read_dir(dir)
        .with_context(|| format!("reading {}", dir.display()))?
        .filter_map(|entry| entry.ok().map(|entry| entry.path()))
        .collect();
    paths.sort();
    for path in paths {
        if path.is_dir() {
            walk(&path, out)?;
        } else {
            out.push(path);
        }
    }
    Ok(())
}

/// Whether `code` calls `function`: its name, not the tail of a longer one, then `(`.
fn calls(code: &str, function: &str) -> bool {
    code.match_indices(function).any(|(at, _)| {
        let before = code[..at].chars().next_back();
        let after = code[at + function.len()..].trim_start();
        !before.is_some_and(|c| c.is_alphanumeric() || c == '_') && after.starts_with('(')
    })
}

/// The pools: each named pool's rule, the cards that draw from it and its members by part.
fn pool_sections(out: &mut String, scripts: &[(String, String)]) -> Result<()> {
    writeln!(out, "\n## {POOLS_HEADING}\n")?;
    writeln!(
        out,
        "Each random pool `crates/cards/src/query.rs` names (`POOLS`): its rule, the cards whose scripts draw from it, and its members today. A card that draws from a pool it is in leaves itself out ([[R387]]).\n"
    )?;
    for pool in POOLS {
        writeln!(out, "### {}\n\n{}\n", pool.name, pool.rule)?;
        let drawn_by: BTreeSet<&str> = scripts
            .iter()
            .filter(|(_, code)| calls(code, pool.call))
            .map(|(id, _)| id.as_str())
            .collect();
        let drawers = catalog()
            .filter(|def| drawn_by.contains(def.id.as_str()))
            .map(label);
        writeln!(out, "Drawn by: {}.\n", joined(drawers))?;
        for (part, members) in (pool.parts)() {
            let members = joined(in_catalog_order(&members).into_iter().map(label));
            if part.is_empty() {
                writeln!(out, "Cards: {members}.")?;
            } else {
                writeln!(out, "- {part}: {members}.")?;
            }
        }
        out.push('\n');
    }
    Ok(())
}

/// `spec/CARDS.md` as `index` writes it, the card scripts read from under `root`.
pub(crate) fn render(root: &Path) -> Result<String> {
    jackioh_cards::register_all();
    let scripts = script_code(&root.join(SCRIPTS_REL))?;
    let mut out = String::from(HEADER);
    out.push('\n');
    keyword_rows(&mut out)?;
    tag_rows(&mut out)?;
    pool_sections(&mut out, &scripts)?;
    let trimmed = out.trim_end().len();
    out.truncate(trimmed);
    out.push('\n');
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::patches::repo_root;
    use jackioh_cards::query::{luck_based, query};

    /// The line of `index` that starts with `start`, or a panic naming it.
    fn line<'a>(index: &'a str, start: &str) -> &'a str {
        index
            .lines()
            .find(|line| line.starts_with(start))
            .unwrap_or_else(|| panic!("spec/CARDS.md has no line starting {start:?}"))
    }

    /// The lines of the pool `name`'s section, up to the next heading.
    fn pool<'a>(index: &'a str, name: &str) -> Vec<&'a str> {
        let heading = format!("### {name}");
        index
            .lines()
            .skip_while(|line| *line != heading)
            .skip(1)
            .take_while(|line| !line.starts_with('#'))
            .collect()
    }

    #[test]
    fn lists_each_keyword_tag_and_pool_of_the_real_catalog() {
        let index = render(&repo_root()).unwrap();
        // §6.1's hand list named neither: #20 has Rush since #3136, S #94 since its set shipped.
        let rush = line(&index, "| Rush |");
        assert!(rush.contains("#20 Pointmaster"), "{rush}");
        assert!(rush.contains("S #94 Tmack Trav"), "{rush}");
        // A keyword only a Radiant face prints says so: Core #86's Rush.
        assert!(rush.contains("(Radiant)"), "{rush}");
        // The retired keyword has no row.
        assert!(!index.contains("| Immune to tribal tag based hate |"));
        // The Jlockeed pool's members: the Stinkyscape and Training Grounds cards the rows left out.
        let jlockeed = pool(&index, "jlockeed").join("\n");
        assert!(jlockeed.contains("S #124 "), "{jlockeed}");
        assert!(jlockeed.contains("TG #45 "), "{jlockeed}");
        assert!(
            jlockeed.contains("Drawn by: C+ #48 Jlockeed's Lobbyist, C+ #52 "),
            "{jlockeed}"
        );
        // The Luck-based pool is exactly the query Gachaholic's script draws from.
        let luck = pool(&index, "luck-based");
        assert!(luck.contains(&"Drawn by: M #101 Gachaholic."), "{luck:?}");
        let members: Vec<String> = in_catalog_order(&query(&luck_based()))
            .into_iter()
            .map(label)
            .collect();
        assert!(
            luck.contains(&format!("Cards: {}.", members.join(", ")).as_str()),
            "{luck:?}"
        );
        assert!(!members.iter().any(|card| card.starts_with("#42 ")));
        // A pool of parts lists each, and the Resources' drawers are found by their verb.
        let weapons = pool(&index, "weapons").join("\n");
        assert!(weapons.contains("- Rare: S #50 "), "{weapons}");
        assert!(weapons.contains("- Legendary: S #58 "), "{weapons}");
        let resources = pool(&index, "resources").join("\n");
        assert!(resources.contains("S #62 "), "{resources}");
        // Every heading a link may name is in the file.
        for heading in headings() {
            assert!(
                index
                    .lines()
                    .any(|line| line.trim_start_matches('#').trim() == heading),
                "{heading}"
            );
        }
    }

    #[test]
    fn a_call_is_the_name_then_its_parenthesis_not_the_tail_of_another_name() {
        assert!(calls("vec![gain_resources(args)]", "gain_resources"));
        assert!(calls("query: Some(crate::query::luck_based ())", "luck_based"));
        assert!(!calls("use effects::{gain_resources};", "gain_resources"));
        assert!(!calls("my_gain_resources(args)", "gain_resources"));
        assert!(!calls("gain_resources_twice(args)", "gain_resources"));
    }

    #[test]
    fn a_card_is_written_as_the_spec_writes_it() {
        jackioh_cards::register_all();
        let card = |id: &str| CATALOG.get(id).unwrap_or_else(|| panic!("{id}"));
        assert_eq!(label(card("core-020")), "#20 Pointmaster");
        assert_eq!(label(card("stinkyscape-094")), "S #94 Tmack Trav");
        assert!(label(card("core-t-rush")).starts_with("T-rush "));
    }
}
