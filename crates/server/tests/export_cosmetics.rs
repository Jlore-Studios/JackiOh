//! Writes `apps/web/src/wire/generated/cosmetics.ts` from `crates/server/cosmetics.json` (#1295,
//! SPEC §11 R1295000): the kinds, the rarities, the longest id a settings text carries (R633) and
//! every entry, each on its own line in the registry's order, so the client draws the ids the
//! server will roll and own without importing the server. CI runs this test and fails on a diff,
//! as it does for `export_config.rs`'s `serverConfig.ts`.

use jackioh_server::config::PLAYER_SETTINGS_TEXT_MAX_LENGTH;
use jackioh_server::cosmetics::{CosmeticKind, CosmeticRarity, shipped};

/// The generated file, relative to this crate.
const OUTPUT: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../apps/web/src/wire/generated/cosmetics.ts"
);

const HEADER: &str = "// Generated by crates/server/tests/export_cosmetics.rs from crates/server/cosmetics.json\n// (R1295000). Do not edit: change the registry and run the test.\n\n";

/// One of the registry's values as one line of JSON.
fn json(value: &impl serde::Serialize) -> String {
    serde_json::to_string(value).unwrap_or_else(|error| panic!("cosmetics.json: {error}"))
}

/// The file's text: the header, the kinds, the rarities, the id cap, then one line per entry.
fn render() -> String {
    let cosmetics = shipped().unwrap_or_else(|error| panic!("cosmetics.json: {error}"));
    let mut out = String::from(HEADER);
    out.push_str(&format!(
        "export const COSMETIC_KINDS = {} as const;\n",
        json(&CosmeticKind::ALL)
    ));
    out.push_str(&format!(
        "export const COSMETIC_RARITIES = {} as const;\n",
        json(&CosmeticRarity::ALL)
    ));
    out.push_str(&format!(
        "export const COSMETIC_ID_MAX_LENGTH = {PLAYER_SETTINGS_TEXT_MAX_LENGTH};\n"
    ));
    out.push_str("export const COSMETICS = [\n");
    for cosmetic in &cosmetics {
        out.push_str(&format!("  {},\n", json(cosmetic)));
    }
    out.push_str("] as const;\n");
    out
}

#[test]
fn every_entry_is_one_line() {
    let cosmetics = shipped().unwrap_or_else(|error| panic!("cosmetics.json: {error}"));
    assert_eq!(render().matches("\n  {\"id\":").count(), cosmetics.len());
}

#[test]
fn export_cosmetics() {
    let text = render();
    let current = std::fs::read_to_string(OUTPUT).unwrap_or_default();
    if current != text {
        if let Some(parent) = std::path::Path::new(OUTPUT).parent() {
            std::fs::create_dir_all(parent).unwrap_or_else(|error| panic!("{}: {error}", parent.display()));
        }
        std::fs::write(OUTPUT, &text).unwrap_or_else(|error| panic!("{OUTPUT}: {error}"));
    }
}
