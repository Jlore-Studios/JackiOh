/// One constant: its name, its TypeScript annotation (if any), its JSON value.
struct Constant {
    name: &'static str,
    annotation: Option<&'static str>,
    json: String,
}

fn constant<T: Serialize + ?Sized>(
    name: &'static str,
    annotation: Option<&'static str>,
    value: &T,
) -> Constant {
    let json =
        serde_json::to_string(value).unwrap_or_else(|error| panic!("{name} does not serialize: {error}"));
    Constant {
        name,
        annotation,
        json,
    }
}

