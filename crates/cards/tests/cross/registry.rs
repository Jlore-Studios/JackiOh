    #[test]
    fn round_trips_every_catalog_id_through_its_expected_filename() {
        let ids = ids();
        // The whole catalog at once: no two cards may claim one path, and every expected path must
        // resolve back to the card that expects it — which is what made `missing-tests.ts` a
        // trustworthy gate.
        let mut seen: IndexMap<String, String> = IndexMap::new();
        for id in &ids {
            let path = expected_rel_path(id, &name_of(id));
            let owner = seen.get(&path).cloned();
            assert_eq!(owner, None, "{path}.ts is claimed by both {owner:?} and {id}");
            seen.insert(path.clone(), id.clone());
            assert_eq!(
                resolve_rel_path(&path, &ids).as_deref(),
                Some(id.as_str()),
                "{path} -> {id}"
            );
            assert!(matches_card(
                &expected_basename(id, &name_of(id)),
                id,
                Some(ids.as_slice())
            ));
        }
        assert_eq!(seen.len(), catalog_size());
    }

