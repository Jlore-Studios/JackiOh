/// `packages/cards/scripts/naming.ts`'s rules, copied (fullsend builder rule 5: the tools' port in
/// `crates/tools/src/patches.rs` is a binary crate this test cannot link). The catalog-id <-> filename
/// convention for the TS card scripts and card tests (BUILD M4-T2 `cards/src/scripts/NNN-slug.ts`,
/// M4-T3 `cards/test/NNN-slug.test.ts`, SPEC §10.9, and patch v0.2.0's set folders, B2.2):
///
///   core-001             "Big D-fender"         src/scripts/001-big-d-fender.ts
///   core-051-1           "KY's Empty Notebook"  src/scripts/051-1-kys-empty-notebook.ts
///   core-t-rush          "Rush Token"           src/scripts/t-rush.ts
///   classic-043          "Plague Nuke"          src/scripts/classic/043-plague-nuke.ts
///   classicplus-012-1    "Devour"               src/scripts/classic-plus/012-1-devour.ts
///   classicplus-t-ai-01  "Helpful Assistant"    src/scripts/classic-plus/t-ai-01-helpful-assistant.ts
///
/// A file's path is its set's folder (none for Core) and a basename `<prefix>-<slug>`, where the prefix
/// is the id minus its set segment, except for Core's named tokens of SPEC §7 — the four shared ones,
/// The Coin and the Ghoul Token — which are filed under the bare prefix (`t-rush`, `t-coin`). An index
/// repeats across sets, so the folder, never the basename alone, says which set a file belongs to.
mod naming {
    use std::cmp::Ordering;

    /// Every shipped id is `<set>-<prefix>`, the set segment holding no hyphen (`classicplus`, B2.2).
    const SET_SEGMENT_SEPARATOR: char = '-';

    /// The catalog's sets' id segments and the folder each one's scripts and tests live in, in catalog
    /// order: Core at the top of `src/scripts/` and `test/`, the others in a folder of their own. A set
    /// that has not shipped (R1420) is listed too: its cards are in the catalog and have files.
    const SET_FOLDERS: &[(&str, &str)] = &[
        ("core", ""),
        ("classic", "classic"),
        ("classicplus", "classic-plus"),
        ("meditative", "meditative"),
    ];

    /// `classic-043` -> `classic`; `None` for an id whose set segment names no shipped set.
    pub fn set_segment_of(id: &str) -> Option<&'static str> {
        let cut = id.find(SET_SEGMENT_SEPARATOR)?;
        if cut == 0 {
            return None;
        }
        let segment = &id[..cut];
        SET_FOLDERS
            .iter()
            .find(|(known, _)| *known == segment)
            .map(|(known, _)| *known)
    }

    /// The folder a catalog id's script and test live in: `""` for Core, `classic`, `classic-plus`.
    pub fn folder_of(id: &str) -> &'static str {
        match set_segment_of(id) {
            Some(segment) => SET_FOLDERS
                .iter()
                .find(|(known, _)| *known == segment)
                .map_or("", |(_, folder)| *folder),
            None => "",
        }
    }

    /// The set segment a folder holds (`""` -> `core`), or `None` for a folder that holds none.
    pub fn segment_of_folder(folder: &str) -> Option<&'static str> {
        SET_FOLDERS
            .iter()
            .find(|(_, known)| *known == folder)
            .map(|(segment, _)| *segment)
    }

    /// Catalog order of the sets (Core, Classic, Classic+, Meditative), for sorting; an unknown set sorts last.
    pub fn set_rank(id: Option<&str>) -> usize {
        match id.and_then(set_segment_of) {
            Some(segment) => SET_FOLDERS
                .iter()
                .position(|(known, _)| *known == segment)
                .unwrap_or(SET_FOLDERS.len()),
            None => SET_FOLDERS.len(),
        }
    }

    /// The filename prefix of a catalog id: the id minus its leading set segment.
    /// `core-001` -> `001`, `core-051-1` -> `051-1`, `core-t-rush` -> `t-rush`,
    /// `classicplus-t-ai-01` -> `t-ai-01`. TS threw on a string that is no catalog id.
    pub fn slug_prefix_of(id: &str) -> Result<String, String> {
        match id.find(SET_SEGMENT_SEPARATOR) {
            Some(cut) if cut > 0 && cut != id.len() - 1 => Ok(id[cut + 1..].to_string()),
            _ => Err(format!(
                "\"{id}\" is not a catalog id (expected \"<set>-<prefix>\", e.g. \"core-043\")"
            )),
        }
    }

    /// A catalog id's prefix, for an id the catalog holds (TS let the throw propagate).
    fn prefix_of_catalog_id(id: &str) -> String {
        slug_prefix_of(id).unwrap_or_else(|error| panic!("{error}"))
    }

    /// `/^\d+$/`.
    fn all_digits(text: &str) -> bool {
        !text.is_empty() && text.bytes().all(|b| b.is_ascii_digit())
    }

    /// `051-1` and `t-rush` are token prefixes; `051` is a card prefix. Nothing nests deeper.
    pub fn is_token_prefix(prefix: &str) -> bool {
        if prefix.starts_with("t-") {
            return true;
        }
        // `/^\d+-\d+$/`
        match prefix.split_once('-') {
            Some((main, sub)) => all_digits(main) && all_digits(sub),
            None => false,
        }
    }

    /// A shared token's prefix (`t-rush`, `t-ai-01`): a token no one card defines. Core's (SPEC §7's
    /// four shared ones, The Coin and the Ghoul Token) are filed under the bare prefix (`t-rush.ts`);
    /// Classic+'s AI generated cards carry their slug like any card (`t-ai-01-helpful-assistant.ts`).
    pub fn is_shared_token_prefix(prefix: &str) -> bool {
        prefix.starts_with("t-")
    }

    /// A card name as a filename slug: lowercase, apostrophes dropped, every other run of
    /// non-alphanumerics collapsed to one `-`.
    ///
    /// Checked against every name, so: "Big D-fender" -> `big-d-fender`, "KY's Empty Notebook" ->
    /// `kys-empty-notebook` (the apostrophe vanishes rather than becoming a dash), "CN-Virus" ->
    /// `cn-virus`, "/fullsend" -> `fullsend`, "Call to Chaos (Core Edition)" ->
    /// `call-to-chaos-core-edition`, `"Miss" Mrow` -> `miss-mrow`, "4-mana 7/7" -> `4-mana-7-7`,
    /// "Forever&" -> `forever`, "BOOM! Big Max" -> `boom-big-max`.
    pub fn slugify(name: &str) -> String {
        let lower: String = name
            .to_lowercase()
            .chars()
            .filter(|c| !matches!(c, '\'' | '\u{2018}' | '\u{2019}'))
            .collect();
        let mut out = String::with_capacity(lower.len());
        let mut in_gap = false;
        for c in lower.chars() {
            if c.is_ascii_lowercase() || c.is_ascii_digit() {
                // `.replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "")`: a gap becomes one dash,
                // and none is left at either end.
                if in_gap && !out.is_empty() {
                    out.push('-');
                }
                in_gap = false;
                out.push(c);
            } else {
                in_gap = true;
            }
        }
        out
    }

    /// The canonical basename (no extension, no folder) for a catalog entry: what `gen-registry.ts`
    /// expected to import and what `missing-tests.ts` printed as the file a card still needs.
    pub fn expected_basename(id: &str, name: &str) -> String {
        let prefix = prefix_of_catalog_id(id);
        // Core's SPEC §7 shared tokens are one word already ("Rush Token" under `t-rush`), so the prefix
        // is the whole filename; anything else carries its slug.
        if is_shared_token_prefix(&prefix) && set_segment_of(id) == Some("core") {
            return prefix;
        }
        format!("{prefix}-{}", slugify(name))
    }

    /// The path under `src/scripts/` or `test/`, without an extension: `classic/043-plague-nuke`.
    pub fn expected_rel_path(id: &str, name: &str) -> String {
        let folder = folder_of(id);
        let basename = expected_basename(id, name);
        if folder.is_empty() {
            basename
        } else {
            format!("{folder}/{basename}")
        }
    }

    /// Whether `basename` (no extension) is the file of catalog id `id`, in that id's own set folder.
    ///
    /// The slug itself is not checked: the prefix decides which card a file belongs to, so a misspelled
    /// slug still lands on the right card. The one hard case is the prefix boundary:
    /// `051-1-kys-empty-notebook` belongs to `core-051-1` and must NOT be read as a slug of `core-051`.
    ///
    /// With `all_ids` (every catalog id) the answer is exact: the longest id prefix of that set the
    /// basename carries wins. Without it the rule is the heuristic "a lone digit segment right after a
    /// card prefix is a token sub-index", which is right for every shipped id except #25 "4-mana 7/7".
    pub fn matches_card(basename: &str, id: &str, all_ids: Option<&[String]>) -> bool {
        if let Some(all_ids) = all_ids {
            return resolve_basename(basename, all_ids, folder_of(id)).as_deref() == Some(id);
        }

        let prefix = prefix_of_catalog_id(id);
        if basename == prefix {
            return true; // the slugless form: `t-rush.ts`
        }
        let Some(rest) = basename.strip_prefix(&format!("{prefix}-")) else {
            return false;
        };
        if rest.is_empty() {
            return false;
        }
        if is_token_prefix(&prefix) {
            return true; // a token id has no sub-token, so the rest is a slug
        }
        // `!/^\d(-|$)/.test(rest)`
        let bytes = rest.as_bytes();
        !(bytes[0].is_ascii_digit() && (bytes.len() == 1 || bytes[1] == b'-'))
    }

    /// Which catalog id a basename in `folder` (`""`, Core's, by default) belongs to, by longest prefix
    /// among that folder's set: `051-1-kys-empty-notebook` matches the prefixes `051` and `051-1`, and
    /// the longer one is the card that owns the file. `None` means the filename names no card of that
    /// set (a typo'd or unpadded prefix), or the folder holds no set.
    pub fn resolve_basename(basename: &str, all_ids: &[String], folder: &str) -> Option<String> {
        let segment = segment_of_folder(folder)?;
        let mut best: Option<String> = None;
        let mut best_length: Option<usize> = None;
        for id in all_ids {
            if set_segment_of(id) != Some(segment) {
                continue;
            }
            let prefix = prefix_of_catalog_id(id);
            if basename != prefix && !basename.starts_with(&format!("{prefix}-")) {
                continue;
            }
            if best_length.is_none_or(|length| prefix.len() > length) {
                best = Some(id.clone());
                best_length = Some(prefix.len());
            }
        }
        best
    }

    /// `classic/043-plague-nuke` -> its folder and basename; a Core path has the folder `""`.
    pub fn split_rel_path(rel_path: &str) -> (&str, &str) {
        match rel_path.rfind('/') {
            None => ("", rel_path),
            Some(cut) => (&rel_path[..cut], &rel_path[cut + 1..]),
        }
    }

    /// Which catalog id a path under `src/scripts/` or `test/` (no extension) belongs to.
    pub fn resolve_rel_path(rel_path: &str, all_ids: &[String]) -> Option<String> {
        let (folder, basename) = split_rel_path(rel_path);
        resolve_basename(basename, all_ids, folder)
    }

    /// A filename prefix as a sortable number, mirroring the engine's index ranking
    /// (`engine/src/catalog.rs` `index_rank`): `001` -> 1, `051-1` -> 51.1 (so a card-defined token
    /// sorts straight after its card), `t-rush` -> +Infinity (shared tokens sort last within their set).
    pub fn prefix_rank(prefix: &str) -> f64 {
        // `/^(\d+)(?:-(\d+))?$/`
        let (main, sub) = match prefix.split_once('-') {
            Some((main, sub)) => (main, Some(sub)),
            None => (prefix, None),
        };
        if !all_digits(main) || sub.is_some_and(|sub| !all_digits(sub)) {
            return f64::INFINITY;
        }
        let text = match sub {
            None => main.to_string(),
            Some(sub) => format!("{main}.{sub}"),
        };
        match text.parse::<f64>() {
            Ok(rank) if rank.is_finite() => rank,
            _ => f64::INFINITY,
        }
    }

    /// A sort key: `[named-no-card tier, set, §5 index rank, path]`.
    pub type SortKey = (u8, usize, f64, String);

    /// The deterministic ordering every tool uses: catalog order — set (Core, Classic, Classic+), then
    /// SPEC §5 index ascending, card-defined tokens after their card, shared tokens last within the set —
    /// and anything that names no catalog card after all of it; then the path, so the order never
    /// depends on the order the filesystem listed a directory.
    pub fn sort_key(path: &str, id: Option<&str>) -> SortKey {
        let tier = if id.is_none() { 1 } else { 0 };
        let set = set_rank(id);
        let rank = match id {
            None => f64::INFINITY,
            Some(id) => prefix_rank(&prefix_of_catalog_id(id)),
        };
        (tier, set, rank, path.to_string())
    }

    /// Compares two `sort_key`s.
    pub fn compare_sort_keys(a: &SortKey, b: &SortKey) -> Ordering {
        if a.0 != b.0 {
            return a.0.cmp(&b.0);
        }
        if a.1 != b.1 {
            return a.1.cmp(&b.1);
        }
        if a.2 != b.2 {
            // Infinity - Infinity is NaN, so compare, don't subtract
            return if a.2 < b.2 {
                Ordering::Less
            } else {
                Ordering::Greater
            };
        }
        a.3.cmp(&b.3)
    }

    /// A legal, unique JS identifier for the namespace import of a script file: paths are unique within
    /// `src/scripts/`, the folder is part of the alias (`classic/043-…` -> `mclassic_043_…`), and the `m`
    /// guard keeps `001-…` from starting an identifier with a digit.
    pub fn module_alias_of(rel_path: &str) -> String {
        let mut out = String::from("m");
        let mut in_gap = false;
        for c in rel_path.chars() {
            if c.is_ascii_alphanumeric() {
                out.push(c);
                in_gap = false;
            } else if !in_gap {
                out.push('_');
                in_gap = true;
            }
        }
        out
    }
}
